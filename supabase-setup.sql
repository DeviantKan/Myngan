create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null, category text not null, price text, old_price text, tag text,
 description text, image_url text not null, affiliate_url text not null,
 is_active boolean not null default true, created_at timestamptz not null default now()
);
alter table public.products enable row level security;
drop policy if exists "Public read active" on public.products;
create policy "Public read active" on public.products for select to anon, authenticated using (is_active=true);
drop policy if exists "Signed-in insert" on public.products;
create policy "Signed-in insert" on public.products for insert to authenticated with check (true);
drop policy if exists "Signed-in update" on public.products;
create policy "Signed-in update" on public.products for update to authenticated using (true) with check (true);
drop policy if exists "Signed-in delete" on public.products;
create policy "Signed-in delete" on public.products for delete to authenticated using (true);